// VP8 data-carrier encoder (RFC 6386). Goal: emit a SYNTACTICALLY VALID VP8
// keyframe whose compressed bitstream CARRIES our tunnel bytes, so the Yandex
// SFU decodes it without error (no PLI) and forwards at full bitrate (~2.4
// Mbit measured for real decodable VP8, vs 0.027 for our garbage-token carrier).
//
// Strategy (v1, simplest valid channel):
//   - A real, fixed, valid VP8 keyframe HEADER (uncompressed + first partition)
//     that declares: all macroblocks use a single intra mode, mb_no_skip_coeff
//     enabled, and NO probability updates (decoder uses default coeff probs).
//   - The token partition then codes DCT coefficients for every block. We do
//     NOT encode real image data; instead we drive the boolean encoder with our
//     payload BITS through the coefficient token tree using DEFAULT probabilities.
//     The decoder reads them back as valid (if meaningless) coefficients — no
//     error — and the joiner re-runs the SAME boolean decode to recover the bits.
//
// This file currently provides the boolean ENCODER (the arithmetic coder at the
// heart of VP8). The keyframe assembly + token coding build on top of it.

