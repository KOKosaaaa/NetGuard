// Keyframe intra-mode trees + probs (RFC 6386 §11.2, §13.4). Modes:
// DC_PRED=0, V_PRED=1, H_PRED=2, TM_PRED=3, B_PRED=4.
var kfYmodeTree = []int{-4, 2, 4, 6, 0, -1, -2, -3}
var kfYmodeProb = []uint8{145, 156, 163, 128}
var uvModeTree = []int{0, 2, -1, 4, -2, -3}
var kfUvModeProb = []uint8{142, 114, 183}

// inSubtree reports whether `value` is reachable from tree node/leaf `node`.
func inSubtree(tree []int, node, value int) bool {
	if node <= 0 {
		return -node == value
	}
	return inSubtree(tree, tree[node], value) || inSubtree(tree, tree[node+1], value)
}

// writeTree encodes `value` through a VP8 token tree with node probabilities.
func (e *boolEncoder) writeTree(tree []int, probs []uint8, value int) {
	idx := 0
	for {
		b := 0
		if !inSubtree(tree, tree[idx], value) {
			b = 1
		}
		e.putBit(int(probs[idx>>1]), b)
		child := tree[idx+b]
		if child <= 0 {
			return
		}
		idx = child
	}
}

// AssembleKeyframeSkip builds a syntactically-valid VP8 KEYFRAME where every
// macroblock is intra DC_PRED and skipped (no coefficients). This is the
// validity-test skeleton: if ffmpeg/libvpx decodes it without error, the
// boolean encoder + header field order are correct, and data-carrying
// coefficients can be added on top. RFC 6386 §9 (header) + §19 (layout).
func AssembleKeyframeSkip(w, h int) []byte {
	fp := newBoolEncoder()
	fp.putFlag(0)        // color_space
	fp.putFlag(0)        // clamping_type
	fp.putFlag(0)        // segmentation_enabled
	fp.putFlag(0)        // filter_type
	fp.putLiteral(0, 6)  // loop_filter_level
	fp.putLiteral(0, 3)  // sharpness_level
	fp.putFlag(0)        // loop_filter_adj_enable
	fp.putLiteral(0, 2)  // log2_nbr_of_DCT_partitions (=0 -> 1 token partition)
	// quant indices
	fp.putLiteral(4, 7)  // y_ac_qi
	fp.putFlag(0)        // y_dc_delta present
	fp.putFlag(0)        // y2_dc_delta present
	fp.putFlag(0)        // y2_ac_delta present
	fp.putFlag(0)        // uv_dc_delta present
	fp.putFlag(0)        // uv_ac_delta present
	// keyframe: refresh_entropy_probs (refresh_last implied)
	fp.putFlag(1)
	// coefficient-probability updates: all "no update"
	for i := 0; i < 4; i++ {
		for j := 0; j < 8; j++ {
			for k := 0; k < 3; k++ {
				for t := 0; t < 11; t++ {
					fp.putBit(int(coefUpdateProbs[i][j][k][t]), 0)
				}
			}
		}
	}
	fp.putFlag(1)         // mb_no_skip_coeff = 1
	fp.putLiteral(128, 8) // prob_skip_false = 128
	// macroblock prediction records (keyframe: in first partition)
	mbw := (w + 15) / 16
	mbh := (h + 15) / 16
	for n := 0; n < mbw*mbh; n++ {
		fp.putBit(128, 1)                       // mb_skip_coeff = 1 (skip), prob 128
		fp.writeTree(kfYmodeTree, kfYmodeProb, 0) // Y mode = DC_PRED
		fp.writeTree(uvModeTree, kfUvModeProb, 0) // UV mode = DC_PRED
	}
	firstPart := fp.finish()
	// empty token partition (all MB skipped -> no tokens read)
	tokenPart := newBoolEncoder().finish()

	fpSize := len(firstPart)
	tag := (fpSize << 5) | (1 << 4) // first_part_size, show_frame=1, version=0, keyframe=0
	out := []byte{
		byte(tag), byte(tag >> 8), byte(tag >> 16),
		0x9d, 0x01, 0x2a,
		byte(w & 0xff), byte((w >> 8) & 0x3f),
		byte(h & 0xff), byte((h >> 8) & 0x3f),
	}
	out = append(out, firstPart...)
	out = append(out, tokenPart...)
	return out
}

// boolEncoder is the VP8 boolean (range) encoder from RFC 6386 §7.3.
type boolEncoder struct {
	out      []byte
	lowValue uint32
	rangeV   uint32
	bitCount int
}

func newBoolEncoder() *boolEncoder {
	return &boolEncoder{rangeV: 255, bitCount: 24}
}

// putBit encodes one boolean `bit` with probability `prob`/256 of being 0.
func (e *boolEncoder) putBit(prob int, bit int) {
	split := 1 + (((e.rangeV - 1) * uint32(prob)) >> 8)
	if bit != 0 {
		e.lowValue += split
		e.rangeV -= split
	} else {
		e.rangeV = split
	}
	// Renormalize: shift out bits while range < 128.
	for e.rangeV < 128 {
		e.rangeV <<= 1
		if e.lowValue&(1<<31) != 0 {
			// carry propagation
			e.propagateCarry()
		}
		e.lowValue <<= 1
		e.bitCount--
		if e.bitCount == 0 {
			e.out = append(e.out, byte(e.lowValue>>24))
			e.lowValue &= 0x00FFFFFF
			e.bitCount = 8
		}
	}
}

// propagateCarry handles the carry bit rippling into already-emitted bytes.
func (e *boolEncoder) propagateCarry() {
	i := len(e.out) - 1
	for i >= 0 && e.out[i] == 0xFF {
		e.out[i] = 0
		i--
	}
	if i >= 0 {
		e.out[i]++
	}
}

// putLiteral encodes `bits` low-order bits of `val` (MSB first) at prob 128.
func (e *boolEncoder) putLiteral(val, bits int) {
	for i := bits - 1; i >= 0; i-- {
		e.putBit(128, (val>>uint(i))&1)
	}
}

// putFlag encodes a single equiprobable bit (prob 128).
func (e *boolEncoder) putFlag(bit int) { e.putBit(128, bit) }

// finish flushes the remaining low-order bits and returns the encoded bytes.
func (e *boolEncoder) finish() []byte {
	for i := 0; i < 32; i++ {
		if e.lowValue&(1<<31) != 0 {
			e.propagateCarry()
		}
		e.lowValue <<= 1
		e.bitCount--
		if e.bitCount == 0 {
			e.out = append(e.out, byte(e.lowValue>>24))
			e.lowValue &= 0x00FFFFFF
			e.bitCount = 8
		}
	}
	return e.out
}
